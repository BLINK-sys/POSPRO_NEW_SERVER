SEEDS = [
    ('offer',        OFFER_TITLE,        OFFER_HTML),
    ('privacy',      PRIVACY_TITLE,      PRIVACY_HTML),
    ('requisites',   REQUISITES_TITLE,   REQUISITES_HTML),
    ('return',       RETURN_TITLE,       RETURN_HTML),
    ('pay-delivery', PAY_DELIVERY_TITLE, PAY_DELIVERY_HTML),
]


def seed():
    for slug, title, html in SEEDS:
        page = StaticPage.query.filter_by(slug=slug).first()
        if page is None:
            db.session.add(StaticPage(
                slug=slug, title=title, content=html, is_active=True,
            ))
            print(f'  CREATE: {slug}', flush=True)
        elif not (page.content or '').strip():
            page.title = title
            page.content = html
            page.is_active = True
            print(f'  FILL (was empty): {slug}', flush=True)
        else:
            print(f'  SKIP (already filled): {slug}', flush=True)
    db.session.commit()


if __name__ == '__main__':
    with app.app_context():
        print('Seeding static pages for footer legal block …', flush=True)
        seed()
    print('Done.', flush=True)
