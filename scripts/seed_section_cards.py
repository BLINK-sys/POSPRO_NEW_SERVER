def _resolve_category_ids(names: list[str]) -> tuple[list[int], list[str]]:
    """Возвращает (ordered_ids, missing_names). Ищет по name регистронезависимо
    среди верхнеуровневых категорий каталога (parent_id IS NULL). Если
    несколько категорий с одинаковым name — берётся с меньшим id."""
    ids: list[int] = []
    missing: list[str] = []
    for name in names:
        # Точное совпадение по name (регистронезависимо), только корни.
        row = (
            Category.query
            .filter(func.lower(Category.name) == name.lower())
            .filter(Category.parent_id.is_(None))
            .order_by(Category.id.asc())
            .first()
        )
        if row is None:
            missing.append(name)
        else:
            ids.append(row.id)
    return ids, missing


def _set_categories(card: SectionCard, category_ids: list[int]) -> None:
    """Пересоздать связи с категориями. Порядок = порядок в списке.
    Копия логики routes/section_cards.py::_set_categories, чтобы не
    тянуть blueprint при запуске скрипта."""
    seen: set[int] = set()
    ordered: list[int] = []
    for cid in category_ids:
        if cid in seen:
            continue
        seen.add(cid)
        ordered.append(cid)

    for old in list(card.categories):
        db.session.delete(old)
    db.session.flush()

    for i, cid in enumerate(ordered):
        db.session.add(SectionCardCategory(
            section_card_id=card.id,
            category_id=cid,
            order=i,
        ))


def _generate_unique_slug(name: str) -> str:
    from routes.products import safe_slugify
    base = safe_slugify(name) or 'section'
    slug = base
    n = 1
    while SectionCard.query.filter_by(slug=slug).first():
        n += 1
        slug = f'{base}-{n}'
    return slug


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--apply', action='store_true',
                        help='реально применить изменения; без флага — dry-run')
    args = parser.parse_args()

    with app.app_context():
        max_order = db.session.query(db.func.max(SectionCard.order)).scalar()
        next_order = (max_order + 1) if max_order is not None else 0

        report_updated: list[tuple[str, int, int]] = []  # (name, id, ncats)
        report_created: list[tuple[str, int]] = []        # (name, ncats)
        report_missing: dict[str, list[str]] = {}          # sphere → missing categories

        for sphere_name, cat_names in PLAN:
            ids, missing = _resolve_category_ids(cat_names)
            if missing:
                report_missing[sphere_name] = missing

            existing = SectionCard.query.filter(
                func.lower(SectionCard.name) == sphere_name.lower()
            ).first()

            if existing is not None:
                _set_categories(existing, ids)
                report_updated.append((sphere_name, existing.id, len(ids)))
            else:
                slug = _generate_unique_slug(sphere_name)
                card = SectionCard(
                    name=sphere_name,
                    slug=slug,
                    target='categories',
                    order=next_order,
                    active=False,
                )
                next_order += 1
                db.session.add(card)
                db.session.flush()
                _set_categories(card, ids)
                report_created.append((sphere_name, len(ids)))

        print('=' * 60)
        print(f'Обновлено существующих: {len(report_updated)}')
        for name, cid, n in report_updated:
            print(f'  · [id={cid:3d}] {name:30s} → {n} категорий')

        print(f'Создано новых:          {len(report_created)}')
        for name, n in report_created:
            print(f'  · {name:30s} → {n} категорий')

        if report_missing:
            print()
            print('ВНИМАНИЕ — не нашли следующие категории:')
            for sphere, misses in report_missing.items():
                for m in misses:
                    print(f'  · {sphere:30s} → «{m}»')

        print('=' * 60)

        if args.apply:
            db.session.commit()
            print('✅ Изменения применены.')
        else:
            db.session.rollback()
            print('⚠️  DRY-RUN: изменения НЕ применены. Запустите с --apply.')


if __name__ == '__main__':
    main()
